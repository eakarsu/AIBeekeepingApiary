'use strict';
const express = require('express');
const pool = require('../config/database');
const { authenticateToken } = require('../middleware/auth');
const { createApiaryReadinessHandlers } = require('../services/runtimeReadiness');
const router = express.Router();
const handlers = createApiaryReadinessHandlers({ pool });
router.post('/apiary-readiness', authenticateToken, handlers.generate);
router.get('/apiary-readiness/history', authenticateToken, handlers.history);
module.exports = router;
